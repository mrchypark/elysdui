import assert from 'node:assert/strict';
import {codeSpans} from '../../assets/ely-code.js';
const source = 'const café = greet("<script>\\\"", 12); // hi';
const spans = codeSpans(source);
assert.equal(spans.find(span => span.text === 'const').kind, 'keyword');
assert.equal(spans.find(span => span.text === 'café').kind, 'variable');
assert.equal(spans.find(span => span.text === 'greet').kind, 'function');
assert.equal(spans.at(-1).kind, 'comment');
for (const span of spans) assert.equal(source.slice(span.start, span.end), span.text);
const json = codeSpans('{"name":"😀", "ok":true, "n":1.5}', true);
assert.equal(json.find(span => span.text === '"name"').kind, 'property');
assert.equal(json.find(span => span.text === '"😀"').kind, 'string');
assert.equal(json.find(span => span.text === 'true').kind, 'constant');
assert.equal(json.find(span => span.text === '1.5').kind, 'number');
assert.equal(codeSpans('"unfinished\nnext')[0].text, '"unfinished');
assert.deepEqual(codeSpans(''), []);
console.log('Code spans: escaped strings, Unicode offsets, JSON keys, comments and incomplete input passed');
