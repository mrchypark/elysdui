import assert from 'node:assert/strict';
import {spawnSync} from 'node:child_process';
import {randomUUID} from 'node:crypto';
import {mkdir,readFile,writeFile} from 'node:fs/promises';
import {join} from 'node:path';
import {fileURLToPath} from 'node:url';
import {loadActivationInputs} from '../ui/gohtmx/tests/browser/palette-activation-inputs.mjs';
import {activationReportName,verifyActivationEvidence} from '../ui/gohtmx/tests/browser/palette-activation-evidence.mjs';
import {runActivationSchemaTests} from './palette-activation-evidence-test.mjs';
runActivationSchemaTests();
const base=fileURLToPath(new URL('../',import.meta.url)),surface=process.env.PALETTE_QUERY_SURFACE||'go-qualified';
assert.equal(process.env.CI,'true','browser execution is restricted to CI');
const runToken=randomUUID(),{assetBodies,fixtureBodies,...trusted}=await loadActivationInputs(base,surface);assert.equal(trusted.dirty,'');
const invocation={...trusted,surface,runToken},output=join(base,'test-results/contracts',activationReportName(surface));await mkdir(join(base,'test-results/contracts'),{recursive:true});
await writeFile(output+'.invocation.json',JSON.stringify(invocation,null,2));
const child=spawnSync(process.execPath,['ui/gohtmx/tests/browser/palette-activation-browser-test.mjs'],{cwd:base,env:{...process.env,PALETTE_ACTIVATION_RUN_TOKEN:runToken},stdio:'inherit'});
assert.equal(child.error,undefined);assert.equal(child.signal,null);
await writeFile(output+'.exit.json',JSON.stringify({revision:trusted.revision,tree:trusted.tree,runToken,exitCode:child.status},null,2));
const report=JSON.parse(await readFile(output,'utf8'));console.log(JSON.stringify({evidenceValidation:'valid',...verifyActivationEvidence(report,invocation,child.status),rawExit:child.status}));
